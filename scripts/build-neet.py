"""Builds the NEET question bank from the Reja1/jee-neet-benchmark dataset (MIT).

Usage: python3 -I scripts/build-neet.py <path-to-neet-raw> <app-root>
Answers are the dataset's, corrected against NTA's keys (see OVERRIDES).
"""
import json, os, sys
from PIL import Image

src, root = sys.argv[1], sys.argv[2]

# Answer corrections, checked against NTA keys and by working each question.
OVERRIDES = {
    # NEET 2024 code T3, NTA revised final key (26 Jul 2024, after the Supreme Court / IIT Delhi review).
    'N24T3025': [1],
    'N24T3122': [1],  # A-III, B-I, C-IV, D-II
    # NEET 2025 code 45: keys disagree on these ambiguous questions, so accept both options.
    'N2545040': [1, 2],
    'N2545152': [1, 2],
}
SUBJECT = {'Physics': 'phy', 'Chemistry': 'che', 'Biology': 'bio', 'Botany': 'bio', 'Zoology': 'bio'}

rows = [json.loads(l) for l in open(os.path.join(src, 'metadata-all.jsonl')) if l.strip()]
rows = [r for r in rows if r['exam_name'] == 'NEET' and r['question_type'] == 'MCQ_SINGLE_CORRECT']
out_dir = os.path.join(root, 'assets', 'neet')
os.makedirs(out_dir, exist_ok=True)

items = []
for r in rows:
    qid = r['question_id']
    im = Image.open(os.path.join(src, r['file_name'])).convert('L')
    w, h = im.size
    im.quantize(16).save(os.path.join(out_dir, f'{qid}.png'), optimize=True)
    ans = OVERRIDES.get(qid) or sorted(int(x) for x in json.loads(r['correct_answer']))
    items.append({'id': qid, 'y': r['exam_year'], 'n': int(os.path.splitext(r['file_name'])[0].split('_')[-1]),
                  's': SUBJECT[r['subject']], 'a': ans, 'w': w, 'h': h})

items.sort(key=lambda x: (x['y'], x['n']))
with open(os.path.join(root, 'src', 'data', 'neet.ts'), 'w') as f:
    f.write('// Generated by scripts/build-neet.py. Do not edit by hand.\n')
    f.write('// Source: Reja1/jee-neet-benchmark (MIT), original NTA question images; answers checked against NTA keys.\n\n')
    f.write("export type NeetSubject = 'phy' | 'che' | 'bio';\n")
    f.write('/** id, exam year, question number in the paper, subject, accepted options (1-4), image width and height. */\n')
    f.write('export type NeetQuestion = { id: string; y: number; n: number; s: NeetSubject; a: number[]; w: number; h: number };\n\n')
    f.write('export const NEET_QUESTIONS: NeetQuestion[] = [\n')
    for it in items:
        f.write('  ' + json.dumps(it, separators=(',', ':')).replace('"id"', 'id').replace('"y"', 'y').replace('"n"', 'n').replace('"s"', 's').replace('"a"', 'a').replace('"w"', 'w').replace('"h"', 'h').replace('"', "'") + ',\n')
    f.write('];\n')
with open(os.path.join(root, 'src', 'data', 'neetImages.ts'), 'w') as f:
    f.write('// Generated by scripts/build-neet.py. Bundled so timed tests never wait on the network.\n')
    f.write('/* eslint-disable @typescript-eslint/no-require-imports */\n')
    f.write('export const NEET_IMAGES: Record<string, number> = {\n')
    for it in items:
        f.write(f"  {it['id']}: require('../../assets/neet/{it['id']}.png'),\n")
    f.write('};\n')
print(len(items), 'questions')
